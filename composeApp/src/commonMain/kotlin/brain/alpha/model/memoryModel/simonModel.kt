// Define the package for the memory model
package brain.alpha.model.memoryModel

// Import the Difficulty enum to manage game difficulty levels
import brain.alpha.model.shared.Difficulty

// Singleton object to manage the Simon game logic and state
object simonModel {

    // Current game difficulty level, default is EASY
    var difficulty: Difficulty = Difficulty.EASY

    // List of available colors for the game
    private val availableColors: List<String> = listOf("Rojo", "Verde", "Azul", "Amarillo")

    // Enumeration to define the possible game states
    enum class GameState { START, MACHINE, PLAYER }

    // Sequence of colors generated by the machine
    private val machineSequence = mutableListOf<String>()

    // Sequence of colors input by the player
    private val playerSequence = mutableListOf<String>()

    // Current state of the game (START, MACHINE, PLAYER)
    private var state = GameState.START

    // Current score of the player
    private var score = 0

    // Computed property to get the delay between colors based on difficulty
    val sequenceDelayMillis: Long
        get() = when (difficulty) {
            Difficulty.EASY -> 1000
            Difficulty.MEDIUM -> 700
            Difficulty.HARD -> 400
        }

    // Increments the player's score by 1
    fun incrementScore() {
        score++
    }

    // Get the delay between showing each color in the sequence based on difficulty
    fun getDelayBetweenColors(): Long = when (difficulty) {
        Difficulty.EASY -> 1500L    // muy lento
        Difficulty.MEDIUM -> 800L   // intermedio
        Difficulty.HARD -> 300L     // muy rápido
    }

    // Get the animation speed for each color based on difficulty
    fun getAnimationSpeed(): Int = when (difficulty) {
        Difficulty.EASY -> 500      // largo entre cada color
        Difficulty.MEDIUM -> 200
        Difficulty.HARD -> 50       // casi inmediato
    }

    // Get the current score of the player
    fun getScore(): Int = score

    // Resets the player's score to zero
    fun resetScore() {
        score = 0
    }

    // Initializes the game, clears sequences, and sets state to MACHINE
    fun startGame() {
        machineSequence.clear()
        playerSequence.clear()
        state = GameState.MACHINE
        addRandomColor()
    }

    // Adds a random color to the machine sequence
    fun addRandomColor() {
        val color = availableColors.random()
        machineSequence.add(color)
    }

    // Adds a player's selected color to their sequence
    fun addPlayerColor(color: String) {
        playerSequence.add(color)
    }

    // Validates the player's last input against the machine's sequence
    fun validatePlayerInput(): Boolean {
        val index = playerSequence.lastIndex // Get the index of the last input

        // Return false if the player's input exceeds the machine's sequence length
        if (index >= machineSequence.size) return false

        // Compare the player's input with the machine's sequence
        return playerSequence[index] == machineSequence[index]
    }

    // Checks if the player's sequence is complete
    fun isPlayerSequenceComplete(): Boolean {
        return playerSequence.size == machineSequence.size
    }

    // Resets the player's input sequence
    fun resetPlayerSequence() {
        playerSequence.clear()
    }

    // Resets the game state, sequences, and score
    fun resetGame() {
        machineSequence.clear()
        playerSequence.clear()
        state = GameState.START
    }

    // Begins the player's turn by clearing the sequence and setting state to PLAYER
    fun beginPlayerTurn() {
        state = GameState.PLAYER
        playerSequence.clear()
    }

    // Retrieves the current machine sequence
    fun getMachineSequence(): List<String> = machineSequence.toList()

    // Retrieves the player's sequence
    fun getPlayerSequence(): List<String> = playerSequence.toList()

    // Retrieves the current game state (START, MACHINE, PLAYER)
    fun getGameState(): GameState = state

    // Updates the current game state
    fun setGameState(newState: GameState) {
        state = newState
    }

    // Calculates the final score based on difficulty
    fun getFinalScore(): Int {
        val multiplier = when (difficulty) {
            Difficulty.EASY -> 1
            Difficulty.MEDIUM -> 2
            Difficulty.HARD -> 3
        }

        // Return the score multiplied by the difficulty level
        return getScore() * multiplier
    }
}